//! The one-time code in the Setup Link (ADR-0062).
//!
//! A code is `<start>-<secret>`: `start` names the server start that generated it, so a code
//! from before a restart can be told apart from a wrong one, and `secret` is 128 random bits.
//! Only the code's hash is kept, in memory, and nothing persists it.

use std::fmt;

use sha2::{Digest, Sha256};
use subtle::ConstantTimeEq;

const START_BYTES: usize = 4;
const SECRET_BYTES: usize = 16;

/// The Setup Link's code, as this server start holds it.
#[derive(Clone)]
pub struct SetupCode {
    start: String,
    hash: [u8; 32],
}

/// What a presented code turned out to be.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum CodeCheck {
    Valid,
    /// Generated by an earlier start of the server.
    Expired,
    Wrong,
}

impl SetupCode {
    /// A new code and its value, which only the Setup Link carries.
    pub fn generate() -> Result<(Self, String), getrandom::Error> {
        let mut start = [0; START_BYTES];
        let mut secret = [0; SECRET_BYTES];
        getrandom::fill(&mut start)?;
        getrandom::fill(&mut secret)?;
        let start = hex::encode(start);
        let value = format!("{start}-{}", hex::encode(secret));
        let hash = Sha256::digest(value.as_bytes()).into();
        Ok((Self { start, hash }, value))
    }

    pub(crate) fn check(&self, presented: &str) -> CodeCheck {
        let Some((start, secret)) = presented.trim().split_once('-') else {
            return CodeCheck::Wrong;
        };
        if !is_hex(start, START_BYTES) || !is_hex(secret, SECRET_BYTES) {
            return CodeCheck::Wrong;
        }
        if start != self.start {
            return CodeCheck::Expired;
        }
        let presented: [u8; 32] = Sha256::digest(presented.trim().as_bytes()).into();
        if bool::from(presented.ct_eq(&self.hash)) {
            CodeCheck::Valid
        } else {
            CodeCheck::Wrong
        }
    }
}

fn is_hex(part: &str, bytes: usize) -> bool {
    part.len() == bytes * 2 && part.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

impl fmt::Debug for SetupCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("SetupCode(..)")
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use super::{CodeCheck, SetupCode};

    #[test]
    fn only_the_generated_value_is_valid() {
        let (code, value) = SetupCode::generate().unwrap();

        assert_eq!(code.check(&value), CodeCheck::Valid);
        assert_eq!(code.check(&format!(" {value}\n")), CodeCheck::Valid);
        let mut wrong = value.clone();
        wrong.replace_range(
            value.len() - 1..,
            if value.ends_with('0') { "1" } else { "0" },
        );
        assert_eq!(code.check(&wrong), CodeCheck::Wrong);
        assert_eq!(code.check(&value.to_uppercase()), CodeCheck::Wrong);
        assert_eq!(code.check(""), CodeCheck::Wrong);
    }

    #[test]
    fn a_code_from_another_start_is_expired() {
        let (code, _) = SetupCode::generate().unwrap();
        let (_, earlier) = SetupCode::generate().unwrap();

        assert_eq!(code.check(&earlier), CodeCheck::Expired);
    }
}
